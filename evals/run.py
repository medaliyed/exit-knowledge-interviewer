"""Run deterministic quality/privacy contracts without modifying human-owned evals."""

import argparse
import os
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--junit", type=Path, default=Path("reports/quality.xml"))
    parser.add_argument("--unit-only", action="store_true")
    args = parser.parse_args(argv)
    args.junit.parent.mkdir(parents=True, exist_ok=True)
    selection = "(eval or redteam) and not live and not infra"
    if args.unit_only:
        selection += " and not db"
    result = subprocess.run(  # noqa: S603 - fixed executable/module and explicit arguments
        [
            sys.executable,
            "-m",
            "pytest",
            "-q",
            "--strict-markers",
            "-m",
            selection,
            f"--junitxml={args.junit.resolve()}",
        ],
        cwd=ROOT,
        check=False,
    )
    if args.junit.exists():
        # This report is generated by the local pytest invocation, not an external document.
        suites = list(ET.parse(args.junit).getroot().iter("testsuite"))  # noqa: S314
        totals = {
            key: sum(int(s.get(key, "0")) for s in suites)
            for key in ("tests", "failures", "errors", "skipped")
        }
        summary = "Quality gate: " + ", ".join(f"{key}={value}" for key, value in totals.items())
        print(summary)
        target = os.environ.get("GITHUB_STEP_SUMMARY")
        if target:
            with Path(target).open("a", encoding="utf-8") as stream:
                stream.write(summary + "\n")
        if not totals["tests"] or totals["failures"] or totals["errors"]:
            return result.returncode or 1
    return result.returncode


if __name__ == "__main__":
    raise SystemExit(main())
